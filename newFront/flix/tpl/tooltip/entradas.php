        <span class="title">Movimientos</span>
    </div>    

    <p>En esta sección, se realizarán todas las operaciones correspondientes a los movimientos que se realicen con los productos que  ingresan  al stock.  Una vez ingresado un producto o lote de productos, automáticamente se generarán dos acciones: </p><br />

    <ul>
        <li>Se generarán los códigos únicos o códigos de trazabilidad</li>
        <li>Se verán reflejadas en el stock del almacén y estantería correspondiente.</li>
    </ul>
    
    <p><b>Entradas:</b> En esta sección se realizarán todos los ingresos de productos al stock. En el listado de entradas se verán reflejados todos aquellos movimientos de altas. Se verán los siguientes campos:</p><br />

    <ul>
        <li><b>Nro:</b> Nro de movimiento interno del sistema.</li><br />
        <li><b>Fecha movimiento:</b> Fechas del movimiento realizado.</li><br />
        <li><b>Proveedor:</b> Nombre del proveedor .</li><br />
        <li><b>Nro despacho:</b> Número  de despacho  en  aduana.</li><br />
        <li><b>Tipo movimiento:</b> Tipo de  movimiento que se realizó con los productos (Alta, Alta por Traspaso, Alta por Devolución).</li><br />
        <li><b>Nro. Tramite Anmat:</b> Número de tramite otorgado por ANMAT.</li><br />
        <li><b>Nro. Comprobante:</b> Número de comprobante  con el cual ingresaron los productos al stock. (Remito o Factura ).</li>
    </ul><br />

    <p>El listado tambien cuenta con las siguientes Herramientas:</p><br />
    <ul>
        <li><b>Cancelable:</b> Sólo podrán cancelarse aquellos movimientos de alta, cuyos productos estén aún en stock. Al cancelar una entrada, se darán de baja los códigos de trazabilidad y unidades del stock.</li><br />
        <li><b>Imprimir:</b> Una vez generado un movimiento de alta, en el icono de impresión,  podremos acceder a la  visualización de las etiquetas generadas en formato PDF.</li>
        <li><b>Detalles:</b> Aquí se podrá visualizar un detalle completo de todos los productos ingresados y  que código de trazabilidad ha sido generado para cada uno de ellos.</li>
    </ul>
