        <span class="title">Pendientes de confirmacion</span>
    </div> <br>   

    <p>En esta seccion se podra realizar un seguimiento de aquellas transaciones que aun tiene pendiente por recepcionar. En caso de algun error en traza desde el mismo se podra realizar el evento de "alertar".<br> 
    En el listado de pendientes se verán reflejados los siguientes campos:</p><br />

    <ul>
        <li><b>Id global:</b> Codigo de transaccion global asinado por ANMAT .</li><br />
        <li><b>Fecha Evento:</b> Fecha en la cual se informo el evento al SNT .</li><br />
        <li><b>Producto Desc :</b> Nombre y presentacion del producto .</li><br />
        <li><b>Nro. Comprobante:</b> Número de comprobante  de la dispensa a informar. (Remito o Factura ).</li><br />
	<li><b>Tipo movimiento:</b> Tipo de  movimiento que se realizó con los productos.</li><br />
        <li><b>GLN de Origen:</b> Numero de GLN del agente que envia la transaccion.</li><br />
    </ul><br />

    <p>El listado tambien cuenta con las siguientes Herramientas:</p><br />
    <ul>
        <li><b>Detalles:</b> Aquí se podrá visualizar un detalle completo de transaccion pendiente y tambien se podra alertar una traza determinada en caso de presentar algun inconveniente.</li>
    </ul>
