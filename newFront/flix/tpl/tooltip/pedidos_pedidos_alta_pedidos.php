    <p>En esta sección, se  podrá ingresar al sistema un  producto  o lote de productos. Aquí también se realizará la generación de trazabilidad, una vez realizada una alta de stock al sistema, tendremos asociadas las unidades a cada código de trazabilidad que haya generado el movimiento. En los campos correspondientes a Proveedor, Productos y Estantería el sistema reconocerá datos en caso que hayan  sido ingresados con anterioridad. De no ser así, podrá presionar sobre el signo mas (+) de color verde ubicado a la derecha y se le abrirá otra ventana donde deberá ingresar los nuevos datos.</p><br />
    
    <p><b>Descripción de datos del formulario de alta de stock:</b></p><br />
    
    <ul>
        <li><b>Proveedor:</b> Campo de auto completado de datos del proveedor (Nombre).</li><br />
        <li><b>Productos:</b> Campo de auto completado de datos del producto (Nombre).</li><br />
        <li><b>Cantidad:</b> Campo de ingreso manual de número de unidades o productos.</li><br />
        <li><b>Lote:</b> Campo de ingreso manual del lote del producto.</li><br />
        <li><b>Vencimiento:</b> Campo de ingreso manual de vencimiento del lote.</li><br />
        <li><b>Estantería:</b> Campo de auto completado de estantería.</li><br />
        <li><b>Nro Remito:</b> Campo de ingreso manual de número de remito con el cual fue enviado el producto.</li><br />
        <li><b>Nro Factura:</b> Campo de ingreso manual de número de factura del producto.</li><br />
        <li><b>Nro Despacho:</b> Campo de ingreso manual de número con el cual fue despachado el producto en aduana.</li><br />
    </ul>
