    <div class="tooltip-title">
        <span class="title">Alta de pedidos</span>
    </div>
    <p>En esta sección se  podrá realizar la carga de un pedido.  Para realizar la alta de un pedido deberá de completar los campos abajo descritos. Es importante tener en cuenta que el sistema por defecto asignara las unidades correspondientes al lote con vencimiento mas cercano, y solo podrá validarse con las unidades asignadas en cuanto a lote y ubicación. Una vez realizada la carga del pedido, debe de imprimirse su orden de trabajo para realizar su preparación.</p><br />
    
    <p><b>Descripción de datos del formulario de alta de stock:</b></p><br />
    
    <ul>
        <li><b>Cliente:</b> Campo de auto completado de nombre o razón social del cliente.</li><br />
        <li><b>Paciente:</b> Campo de auto completado de nombre del paciente.</li><br />
        <li><b>Productos:</b> Campo de auto completado de GTIN o nombre del producto.</li><br />
        <li><b>Cantidad:</b> Campo de ingreso manual de número de unidades o productos.</li><br />
        <li><b>Lote:</b> Campo de ingreso manual del lote del producto, solo completar en caso de querer utilizar un lote especial.</li><br />
        <li><b>Utilizar dirección del cliente:</b> En caso de seleccionar Si, se completara con aquellos datos cargados en el abm de clientes.</li><br />
        <li><b>Calle:</b> Campo de ingreso manual, calle de entrega del pedido.</li><br />
        <li><b>Altura:</b> Campo de ingreso manual, altura de la calle de entrega del pedido.</li><br />
        <li><b>Piso:</b> Campo de ingreso manual, piso de la dirección cargada.</li><br />
        <li><b>Departamento:</b> Campo de ingreso manual.</li><br />
        <li><b>Código postal:</b> Campo de ingreso manual.</li><br />
        <li><b>Teléfono:</b> Campo de ingreso manual, teléfono de contacto.</li><br />
        <li><b>Localidad:</b> Campo auto completado,  nombre de la localidad de entrega.</li><br />
        <li><b>Nro Remito:</b> Campo de ingreso manual, Nro de remito asociado al pedido.</li><br />
        <li><b>Nro Factura:</b> Campo de ingreso manual, Nro de factura asociada al pedido.</li><br />
        <li><b>Observaciones:</b> Campo de ingreso manual, comentarios sobre el pedido.</li><br />
    </ul>
</div>