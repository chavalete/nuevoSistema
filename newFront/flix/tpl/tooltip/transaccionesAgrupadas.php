    <p>Que es una transaccion?</p><br />
    <p> Una transaccion es la recepcion/envio de un producto hacia otro agente (1 traza 1 transaccion)</p><br /><br />
    <p>Que es una transaccion Agrupada?</p><br />
    <p>Es el conjunto de transacciones realizadas agrupadas por el Numero de Referencia.</p><br />
    <p>En esta seccion se podra realizar un seguimiento de todas las transacciones realizadas y en caso de error podra realizar la correcion necesaria para luego realizar su reenvio. En el listado de transacciones agrupadas se verán reflejados los siguientes campos:</p><br />

    <ul>
        <li><b>Nro Referencia:</b> Nro de Referencia establecido con el cliente para identificar los movimientos.</li><br />
        <li><b>Codigo de Transaccion:</b> Codigo de transaccion asignado por el SNT.</li><br />
        <li><b>GLN de Origen:</b> Numero de GLN del agente que envia la transaccion.</li><br />
        <li><b>GLN de Destino:</b> Numero de GLN del agente que recibe la transaccion.</li><br />
        <li><b>Tipo movimiento:</b> Tipo de  movimiento que se realizó con los productos.</li><br />
        <li><b>Nro. Comprobante:</b> Número de comprobante  con el cual ingresaron los productos al stock. (Remito o Factura ).</li>
        <li><b>Error Desc:</b> Mensaje de error en caso de error en el envio. .</li>
    </ul><br />

    <p>El listado tambien cuenta con las siguientes Herramientas:</p><br />
    <ul>
        <li><b>Cancelar:</b> Posibilidad de cancelar una transaccion en caso de error..</li><br />
        <li><b>Detalles:</b> Aquí se podrá visualizar un detalle completo de transaccion realizada.</li>
        <li><b>Autogestion:</b> Solo se vera reflejado en caso de error, aquí se podrá visualizar un detalle completo de transaccion realizada y se podran realizar las correcciones necesarias su reenvio.</li>
        <li><b>Enviar Transaccion:</b> Solo se vera reflado en caso de error, una vez realizadas las modificaciones sobre la transaccion con error, haciendo click podra reenviar la transaccion al SNT.</li>
    </ul>
