    <p>En esta sección, se realizarán todas las operaciones correspondientes a los movimientos que se realicen con los productos que  salen  del stock.  Una vez finalizado el movimiento, automáticamente se generarán dos acciones:</p><br />
    
    <ul>
        <li>Se generara el remito o nota de carga</li>
        <li>Comenzaran a regir los dias de alquiler en caso de que el producto sea alquilable.</li>
    </ul><br>

    <p><b>Listado de pedidos:</b> En el mismo se verán reflejados los siguientes campos:</p><br />

    <ul>
        <li><b>Nro:</b> Número de movimiento interno del sistema.</li><br />
        <li><b>Fecha/hora:</b> Fecha del movimiento realizado.</li><br />
        <li><b>Nombre cliente:</b> nombre del cliente.</li><br />
        <li><b>Nro orden de compra:</b> Número de orden de compra o pedido.</li><br />
        <li><b>Nro nota de carga:</b> número de nota de carga.</li>
        <li><b>Nro comprobante:</b> Número de comprobante del remito o factura.</li><br />
        <li><b>Tipo movimiento:</b> Datos del tipo de operación realizada.</li>
    </ul><br /><br />

    <p>El listado tambien cuenta con las siguientes Herramientas:</p><br />
    
    <ul>
        <li><b>Detalles:</b> Aquí se podrá visualizar un detalle completo de las salidas  y  que productos fueron utilizados en el movimiento.</li><br />
        <li><b>Finalizar Movimiento:</b> Una vez completado los datos del pedido, debera finalizar el movimiento para imprimir el remito.</li><br />
        <li><b>Imprimir:</b> Una vez finalizado el movimiento podra imprimir el remito o nota de carga.</li><br />
    </ul>
