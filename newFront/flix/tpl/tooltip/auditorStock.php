        <span class="title">Auditor de stock</span>
    </div>

    <p>Herramienta de consulta para conocer la historia de un producto. Útil para encontrar posibles diferencias en el stock.</p><br />
    
    <ul>
        <li><b>Fecha mov:</b> Fecha y hora en la que fue realizado el movimiento.</li><br />
        <li><b>Producto nombre:</b> Nombre y presentación del producto.</li><br />
        <li><b>Tipo movimiento:</b> Tipo de movimiento realizado (Alta, Baja, Traspaso, Devolución).</li><br />
        <li><b>Comprobante:</b> Numero de comprobante utilizado en el movimiento.</li><br />
        <li><b>Almacén:</b> Nombre del almacén en el cual se encuentra el producto.</li><br />
        <li><b>Estanteria:</b> Nombre  de estantería en la cual se encuentra el producto.</li><br />
        <li><b>Lote Desc:</b> Lote del producto.</li><br />
        <li><b>Vencimiento:</b> Fecha de vencimiento.</li><br />
        <li><b>Cantidad:</b> Unidades ingresadas al stock.</li><br />
        <li><b>Total:</b> Total acumulado.</li><br />
    </ul><br />
    
    <p><b>El listado también cuenta con las siguientes Herramientas:</b></p>
    
    <ul>
        <li><b>Detalles:</b> Aquí se podrá visualizar un detalle completo de la operación realizada y  que código de trazabilidad ha sido generado para cada uno de los productos, estarán presentados en dos secciones</li>
    </ul>
