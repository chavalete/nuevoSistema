        <span class="title">Hoja de Ruta (HDR)</span>
    </div>

    <p>En esta sección se podrá realizar la gestión de las hojas de ruta. Una HDR estará compuesta por aquellos pedidos preparados o que no hayan sido entregados en otra instancia y serán asignados a un distribuidor.<br>
    En el listado que vemos a continuación se podrá visualizar el detalle completo de cada hoja asignada a un distribuidor.</p><br />

    <ul>
        <li><b>Nro. de Hoja :</b> Nro de hoja de ruta, numeración interna útil para referencias.</li><br />
        <li><b>Fecha/hora:</b> Fecha y hora de creación de la HDR.</li><br />
        <li><b>Distribuidor:</b> Nombre del distribuidor asignado a esa HDR.</li><br />
        <li><b>Observaciones:</b> Comentarios sobre la HDR.</li>
    </ul><br /><br />

    <p>El listado también cuenta con las siguientes Herramientas:</p><br />
    
    <ul>
	<li><b>Cancelar:</b> Aquí se podrá cancelar una HDR que no tenga pedidos confirmados/entregados.</li><br />
        <li><b>Detalles:</b> Aquí se podrá visualizar un detalle completo de la HDR, que pedidos fueron asignados y en que estado se encuentran.</li><br />
        <li><b>Imprimir:</b> Aquí se podrá imprimir la HDR.</li><br />
    </ul>
