    <p>En esta sección se podrá realizar la carga de pedidos, los  mismos reservan stock al momento de su carga . Una vez realizado el pedido deberá de imprimirse su orden de pedido (Impresora) para poder realizar su validación en el modulo de Movimientos->Salidas</p><br />

    <ul>
        <li><b>Nro. Pedido :</b> Nro de Pedido.</li><br />
        <li><b>Fecha/hora:</b> Fecha y hora de carga del pedido.</li><br />
        <li><b>Nombre cliente:</b> Nombre del cliente.</li><br />
        <li><b>Estado:</b> Estado en el cual se encuentra un pedido(En preparación, Preparado, etc, etc..).</li><br />
        <li><b>Nro. Factura:</b> Número de factura asociado al pedido.</li><br />
        <li><b>Nro. Remito:</b> Número de remito asociado al pedido.</li><br />
        <li><b>Observaciones:</b> Comentarios sobre el pedido.</li>
    </ul><br /><br />

    <p>El listado también cuenta con las siguientes Herramientas:</p><br />
    
    <ul>
	<li><b>Cancelar:</b> Aquí se podrá cancelar un pedido mientras el mismo no haya sido preparado..</li><br />
        <li><b>Detalles:</b> Aquí se podrá visualizar un detalle completo del pedido.</li><br />
        <li><b>Imprimir:</b> Aquí se podrá imprimir la orden de pedido para realizar su preparación.</li><br />
    </ul>
