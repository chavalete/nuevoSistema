    <ul>
        <li><b>Nro:</b> Nro de movimiento.</li><br />
        <li><b>Cliente:</b> Nombre de cliente.</li><br />
        <li><b>Domicilio entrega:</b>Campo manual, Domicilio en el cual sera entregado el pedido.</li><br />
        <li><b>Medico:</b> Campo autocompletado(debe existir en el abm de medicos).</li><br />
        <li><b>Afiliado:</b> Campo autocompletado(debe existir en el abm de pacientes).</li><br />
        <li><b>Obra Social:</b> Campo autocompletado(debe existir en el abm de obras sociales).</li><br />
        <li><b>Vendedor:</b> Campo autocompletado(debe existir en el abm de vendedores).</li><br />
        <li><b>Distribuidor:</b> Campo autocompletado(debe existir en el abm de distribuidores).</li><br />
        <li><b>Dias de alquiler:</b> Campo manual, solo debe ser completado de ser necesario.</li><br />
        <li><b>Nro Factura:</b> Campo manual, numero de factura del pedido.</li><br />
        <li><b>Nro Remito:</b> Campo manual, numero de remito del pedido.</li><br />
	<li><b>Nro Nota de Carga:</b> Campo manual, numero de nota de carga.</li><br />
        <li><b>Tipo movimiento:</b> Tipo de operación realizada.</li><br />
        <li><b>Fecha:</b> Fecha de operación realizada.</li><br />
    </ul><br />

    <p><b>Detalles de Productos</b></p><br />

    <ul>
        <li><b>Código único:</b> Código de trazabilidad asignado para el producto.</li><br />
        <li><b>Producto:</b> Nombre y presentación del producto.</li><br />
        <li><b>PM:</b> Número de productos médico en ANMAT.</li><br />
        <li><b>Lote:</b> Lote del producto.</li><br />
        <li><b>Lote vence:</b> Vencimiento del lote del productos.</li><br />
    </ul><br />
    <p>Herramientas:</p><br />
    <ul>
        <li><b>Edición:</b> De todos aquellos campos requeridos para finalizar un movimiento(Cliente, domicilio entrega, nro de remito/factura o nota de carga).</li><br />
        <li><b>Renovar:</b> Podra seleccionar aquellos productos a renovar de ser necesario, seleccionando los codigos correspondientes y presiondando el icono de alerta, esto generara un nuevo movimiento el cual debe ser completado desde la edición.</li>
    </ul>
